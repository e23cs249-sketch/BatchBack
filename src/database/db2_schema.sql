-- BatchBack Db2 schema baseline.
-- Apply once to a dedicated BatchBack schema before enabling DATABASE_MODE=db2.

CREATE TABLE SUPPLIERS (
    SUPPLIER_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    CONTACT_EMAIL VARCHAR(254),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    PRODUCT_NAME VARCHAR(200) NOT NULL,
    PRODUCT_CATEGORY VARCHAR(120) NOT NULL,
    SUPPLIER_ID VARCHAR(80),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_PRODUCT_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID)
);

CREATE TABLE BATCHES (
    BATCH_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    PRODUCT_ID VARCHAR(80) NOT NULL,
    PRODUCT_NAME VARCHAR(200) NOT NULL,
    PRODUCT_CATEGORY VARCHAR(120) NOT NULL,
    MANUFACTURER VARCHAR(200) NOT NULL,
    PRODUCTION_DATE DATE NOT NULL,
    EXPIRY_DATE DATE NOT NULL,
    PRODUCTION_QUANTITY BIGINT NOT NULL CHECK (PRODUCTION_QUANTITY >= 0),
    BATCH_QUALITY_STATUS VARCHAR(80) NOT NULL,
    RECALL_STATUS VARCHAR(80) NOT NULL DEFAULT 'Clear',
    RISK_LEVEL VARCHAR(20) NOT NULL CHECK (RISK_LEVEL IN ('Critical', 'High', 'Medium', 'Low')),
    CONSTRAINT FK_BATCH_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CK_BATCH_DATES CHECK (EXPIRY_DATE >= PRODUCTION_DATE)
);

CREATE TABLE PRODUCTION_RECORDS (
    PRODUCTION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID VARCHAR(80) NOT NULL,
    FACILITY_NAME VARCHAR(200) NOT NULL,
    PRODUCED_AT TIMESTAMP NOT NULL,
    QUANTITY BIGINT NOT NULL CHECK (QUANTITY >= 0),
    DETAILS CLOB,
    CONSTRAINT FK_PRODUCTION_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID)
);

CREATE TABLE WAREHOUSES (
    WAREHOUSE_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    LOCATION VARCHAR(200) NOT NULL
);

CREATE TABLE DISTRIBUTORS (
    DISTRIBUTOR_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    LOCATION VARCHAR(200)
);

CREATE TABLE RETAIL_DESTINATIONS (
    DESTINATION_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    LOCATION VARCHAR(200) NOT NULL
);

CREATE TABLE SHIPMENTS (
    SHIPMENT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID VARCHAR(80) NOT NULL,
    PRODUCT VARCHAR(200) NOT NULL,
    PRODUCTION_DATE DATE NOT NULL,
    EXPIRY_DATE DATE NOT NULL,
    SHIPPED_QUANTITY BIGINT NOT NULL CHECK (SHIPPED_QUANTITY >= 0),
    DESTINATION VARCHAR(200) NOT NULL,
    INVENTORY_QUANTITY BIGINT NOT NULL DEFAULT 0 CHECK (INVENTORY_QUANTITY >= 0),
    RECALL_STATUS VARCHAR(80) NOT NULL DEFAULT 'Clear',
    SHIPMENT_STATUS VARCHAR(80) NOT NULL,
    SHIPPED_DATE TIMESTAMP,
    WAREHOUSE_ID VARCHAR(80),
    DISTRIBUTOR_ID VARCHAR(80),
    DESTINATION_ID VARCHAR(80),
    CONSTRAINT FK_SHIPMENT_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID),
    CONSTRAINT FK_SHIPMENT_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID),
    CONSTRAINT FK_SHIPMENT_DISTRIBUTOR FOREIGN KEY (DISTRIBUTOR_ID) REFERENCES DISTRIBUTORS(DISTRIBUTOR_ID),
    CONSTRAINT FK_SHIPMENT_DESTINATION FOREIGN KEY (DESTINATION_ID) REFERENCES RETAIL_DESTINATIONS(DESTINATION_ID)
);
CREATE INDEX IDX_SHIPMENTS_BATCH ON SHIPMENTS(BATCH_ID);
CREATE INDEX IDX_SHIPMENTS_DESTINATION ON SHIPMENTS(DESTINATION);

CREATE TABLE INVESTIGATIONS (
    INVESTIGATION_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    BATCH_ID VARCHAR(80) NOT NULL,
    EXECUTION_MODE VARCHAR(40) NOT NULL,
    STATUS VARCHAR(40) NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    RESULT_JSON CLOB NOT NULL,
    CONSTRAINT FK_INVESTIGATION_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID)
);
CREATE TABLE RISK_ASSESSMENTS (
    ASSESSMENT_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    INVESTIGATION_ID VARCHAR(80) NOT NULL,
    RISK_CATEGORY VARCHAR(40) NOT NULL,
    RISK_SCORE INTEGER NOT NULL CHECK (RISK_SCORE BETWEEN 0 AND 100),
    CONFIDENCE DECIMAL(5,2),
    EXPLANATION CLOB NOT NULL,
    RECOMMENDATIONS CLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_RISK_INVESTIGATION FOREIGN KEY (INVESTIGATION_ID) REFERENCES INVESTIGATIONS(INVESTIGATION_ID)
);

CREATE TABLE RECALL_CASES (
    RECALL_ID VARCHAR(80) NOT NULL PRIMARY KEY,
    BATCH_ID VARCHAR(80) NOT NULL,
    STATUS VARCHAR(40) NOT NULL,
    CREATED_BY VARCHAR(80) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_RECALL_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID)
);
CREATE TABLE APPROVALS (
    APPROVAL_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECALL_ID VARCHAR(80) NOT NULL,
    DECISION VARCHAR(20) NOT NULL CHECK (DECISION IN ('approved', 'rejected')),
    ACTOR VARCHAR(80) NOT NULL,
    REASON VARCHAR(1000) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_APPROVAL_RECALL FOREIGN KEY (RECALL_ID) REFERENCES RECALL_CASES(RECALL_ID)
);
CREATE TABLE RECALL_ACTIONS (
    ACTION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECALL_ID VARCHAR(80) NOT NULL,
    DESTINATION VARCHAR(200) NOT NULL,
    ACTION_TYPE VARCHAR(80) NOT NULL,
    STATUS VARCHAR(40) NOT NULL,
    PROGRESS INTEGER NOT NULL DEFAULT 0 CHECK (PROGRESS BETWEEN 0 AND 100),
    SIMULATED SMALLINT NOT NULL DEFAULT 0 CHECK (SIMULATED IN (0, 1)),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_ACTION_RECALL FOREIGN KEY (RECALL_ID) REFERENCES RECALL_CASES(RECALL_ID)
);

CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR(200) NOT NULL,
    MESSAGE VARCHAR(2000) NOT NULL,
    SEVERITY VARCHAR(20) NOT NULL,
    SOURCE VARCHAR(80) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE TABLE AUDIT_LOGS (
    EVENT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACTOR VARCHAR(80) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    RECALL_ID VARCHAR(80),
    BATCH_ID VARCHAR(80),
    EVENT_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    DETAILS CLOB NOT NULL
);
CREATE INDEX IDX_AUDIT_RECALL ON AUDIT_LOGS(RECALL_ID);
